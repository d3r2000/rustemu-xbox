// D3D::SetFence — the inner function called by InsertFence(0) and BlockOnFence(token,4).
// XDK 5344+: InsertFence is a thin thunk (push 0; call SetFence; ret), so we hook SetFence
// directly. Address-agnostic: g_pDevice bytes (0x03-0x06) wildcarded.
// 2026-04-05: Added bytes 0x0D-0x0F to distinguish from EdgeAntiAlias (0x002EC270 in SM)
// which has identical prologue but `jb +5; call` instead of `push edi; jb +0xE; mov eax,`.
// Old 9-entry pattern matched EdgeAntiAlias via 1-byte tolerance. Now 12 entries.
static INSERT_FENCE: &[OovpaEntry] = &[
    ov!(0x00, 0x56), // push esi
    ov!(0x01, 0x8B),
    ov!(0x02, 0x35), // mov esi, [g_pDevice]  (0x03-0x06 = device addr, wildcarded)
    ov!(0x07, 0x8B),
    ov!(0x08, 0x06), // mov eax, [esi]
    ov!(0x09, 0x3B),
    ov!(0x0A, 0x46),
    ov!(0x0B, 0x04), // cmp eax, [esi+4]
    ov!(0x0C, 0x57), // push edi          (EdgeAntiAlias has 0x72=jb here — discriminator)
    ov!(0x0D, 0x72), // jb +N             (SetFence: jb over the KickOff call)
    ov!(0x0F, 0xA1), // mov eax, [imm32]  (SetFence reads g_pDevice again)
];

